export function localizeDesktopText(locale: LocaleCode, text: string | undefined): string {
  if (!text || locale === "en") {
    return text || "";
  }

  const localeText = sharedLocaleText[locale] || compactLocaleText[locale];
  if (localeText?.[text]) {
    return localeText[text];
  }
  if (text.endsWith(".")) {
    const withoutPeriod = text.slice(0, -1);
    if (localeText?.[withoutPeriod]) {
      return `${localeText[withoutPeriod]}.`;
    }
  }

  let translated = text;
  for (const [pattern, replacement] of markdownHeadingsByLocale[locale] || []) {
    translated = translated.replace(pattern, replacement);
  }

  return translated;
}
